import 'package:investment_ontology_serverpod_server/src/ontology/disclosure/market_share_facts.dart';
import 'package:test/test.dart';

void main() {
  test('연도 머리글 + 당사(회사 이름) 줄의 % 값만 읽는다 (한온시스템·서울보증보험)', () {
    const t = '''
(2) 시장점유율
국내 자동차 공조 시장의 점유율 추이입니다.
구 분 | 2025년 | 2024년 | 2023년
한온시스템 | 50% | 48% | 46%
두 원 공 조 | 35% | 36% | 38%
기 타 | 7% | 8% | 8%
''';
    final rows = MarketShareFacts.parse(t, owner: '한온시스템(주)');
    expect(rows.map((r) => (r.year, r.value)), [
      (2025, 50.0),
      (2024, 48.0),
      (2023, 46.0),
    ]);
    // 설명 문장은 제목이 아니고 "(2) 시장점유율"은 벗기면 비므로 '당사'.
    expect(rows.first.label, '당사');

    const t2 = '''
나. 시장점유율
구 분 | 2025년 3분기 | 2024년 | 2023년
당사 점유율 | 전체 보증시장 대비 | 23.9% | 23.7% | 24.1%
민간 보증시장 대비 | 55.0% | 55.1% | 56.0%
''';
    final rows2 = MarketShareFacts.parse(t2, owner: '서울보증보험(주)');
    // 3분기 칸은 연도가 아니라 빼고, 이름이 둘로 나뉜 줄도 오른쪽 끝 기준으로 맞춘다.
    expect(rows2.map((r) => (r.year, r.value)), [(2024, 23.7), (2023, 24.1)]);
    expect(rows2.first.label, '당사');
  });

  test('순위표·경쟁사 줄·뒤집힌 표·점유율 말이 없는 표는 읽지 않는다', () {
    const t = '''
순위 | 지역 | 업체명 | 시장점유율
1 | Ronbay (中) | 119,000 | 9.5%
2 | 에코프로비엠 | 105,000 | 8.4%
년도 | 구분 | 한국앤컴퍼니(*1) | 세방전지
2024 | 점 유 율 | 22.3% | 39.8%
구 분 | 2025년 | 2024년 | 2023년
매출액 | 1,200 | 1,100 | 1,000
''';
    expect(MarketShareFacts.parse(t, owner: '(주)에코프로비엠'), isEmpty);
    expect(MarketShareFacts.parse(t, owner: '한국앤컴퍼니(주)'), isEmpty);
  });

  test('단위가 %인 표는 숫자만 있어도 받고, 100을 넘는 값은 버린다', () {
    const t = '''
(3) 국내 냉매 시장점유율
(단위 : %)
구 분 | 2025년 | 2024년
당사 | 31.2 | 28.9
경쟁사 A | 20.1 | 22.0
''';
    final rows = MarketShareFacts.parse(t, owner: '(주)테스트');
    expect(rows.map((r) => (r.year, r.value)), [(2025, 31.2), (2024, 28.9)]);
    expect(rows.first.label, '국내 냉매');
  });

  test('둘째 머리글(수주량 | 점유율)이 있으면 점유율 칸을, 순위 쌍 표와 자회사 줄은 버린다', () {
    const t = '''
(가) 시장점유율 추이
| (단위 : 천GT)
구 분 | 2025년 | 2024년 | 2023년
수주량 | 점유율 | 수주량 | 점유율 | 수주량 | 점유율
HD현대중공업 | 7,057 | 28.5% | 2,792 | 15.1% | 5,304 | 33.0%
삼성중공업 | 4,610 | 18.7% | 3,758 | 20.3% | 3,883 | 24.1%
''';
    final rows = MarketShareFacts.parse(t, owner: '삼성중공업(주)', bsnsYear: 2025);
    expect(rows.map((r) => (r.year, r.value)), [
      (2025, 18.7),
      (2024, 20.3),
      (2023, 24.1),
    ]);

    const t2 = '''
국내 조선사 시장점유율
구분 | 2025년 | 2024년 | 2023년
대한조선 | 15.7% | HD현대중공업 | 10.2% | HD현대삼호 | 10.3%
태반주사제 점유율
구분 | 제품 | 2025년 | 2024년 | 2023년
태반주사제 | 라이넥주 | 녹십자웰빙 | 77.1 | 녹십자웰빙 | 77.8 | 녹십자웰빙 | 80.7
''';
    expect(MarketShareFacts.parse(t2, owner: '대한조선 주식회사'), isEmpty);

    // 머리글에 연도 아닌 칸("2025년 3분기말")이 섞이고 둘째 머리글이 있으면 자리를 셀 수 없다.
    const t3 = '''
주1) 4대 시중은행 및 인터넷전문은행 간 점유율
[원화대출금] | (단위 : 백만원, %)
구분 | 2025년 3분기말 | 2024년말 | 2023년말
잔액 | 점유율 | 잔액 | 점유율 | 잔액 | 점유율
케이뱅크 | 17,855,166 | 1.27% | 16,266,586 | 1.20% | 13,837,134 | 1.09%
''';
    expect(MarketShareFacts.parse(t3, owner: '주식회사 케이뱅크'), isEmpty);
    expect(MarketShareFacts.parse(t2, owner: '(주)녹십자'), isEmpty);
  });

  test('보고서 연도보다 7년 넘게 앞선 옛 추이표는 받지 않는다', () {
    const t = '''
소주 시장점유율 추이
구분 | 회사 | '07 | '08 | '09
소 주 | 하이트진로 | 50.0 | 51.4 | 48.3
''';
    expect(
      MarketShareFacts.parse(t, owner: '하이트진로(주)', bsnsYear: 2025),
      isEmpty,
    );
  });

  test('이 회사 줄이 없고 값 줄이 하나뿐인 제품별 표는 그 회사 점유율이다 (삼성전자)', () {
    const t = '''
(국내외 시장여건 등)1) TV산업
TV 시장 수요는 2024년 2억 883만대를 기록하였습니다.
제 품 | 2024년 | 2023년 | 2022년
TV | 28.3% | 30.1% | 29.7%
※ 시장점유율은 외부조사기관인 Omdia의 세계시장점유율 자료(금액 기준)를 활용하였습니다.
2) 모바일 산업
제 품 | 2024년 | 2023년 | 2022년
스마트폰 | 18.3% | 19.7% | 21.7%
※ 시장점유율은 외부조사기관인 TechInsights의 세계시장점유율 자료(수량 기준)를 활용하였습니다.
시장점유율 추이
구 분 | 2025년 | 2024년 | 2023년
한온시스템 | 50% | 48% | 46%
두 원 공 조 | 35% | 36% | 38%
''';
    final rows = MarketShareFacts.parse(t, owner: '삼성전자(주)', bsnsYear: 2024);
    // 증감율 줄은 점유율이 아니다.
    const growth = '''
편의점 시장점유율
구분 | 2025년 | 2024년 | 2023년
매출 증감율 | -9.1 | -2.5 | 3.7
''';
    expect(MarketShareFacts.parse(growth, owner: '(주)지에스리테일'), isEmpty);
    expect(rows.map((r) => (r.label, r.year, r.value)), [
      ('TV', 2024, 28.3),
      ('TV', 2023, 30.1),
      ('TV', 2022, 29.7),
      ('스마트폰', 2024, 18.3),
      ('스마트폰', 2023, 19.7),
      ('스마트폰', 2022, 21.7),
    ]);
  });
}
